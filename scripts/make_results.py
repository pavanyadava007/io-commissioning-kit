"""Write docs/RESULTS.md and the README results block from the JSON outputs of real runs.

Never edit the numbers by hand: rerun `make campaign` / `make results`.
"""

import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
LABELS = {
    "swap": "Swapped channels (crossed cores)",
    "open": "Open circuit",
    "scaling": "Scaling mismatch",
    "inverted": "Inverted DI contact (NO/NC)",
    "stuck": "Stuck / frozen value",
    "polarity": "DO polarity reversal",
    "noise": "Noise",
    "scaling/span": "Scaling: span 25 % too large",
    "scaling/widen": "Scaling: range widened both ends (mid-scale unchanged)",
    "scaling/rtd-curve": "Scaling: wrong RTD curve (alpha 0.003926)",
}


def pct(v):
    return "-" if v is None else f"{v:.1f} %"


def class_table(rows: dict) -> list[str]:
    out = ["| Fault class | Faults | Kit detected | Kit classified | Naive detected |",
           "|---|---|---|---|---|"]
    for k, v in rows.items():
        out.append(f"| {LABELS.get(k, k)} | {v['n']} | {pct(v['kit_detected_pct'])} | "
                   f"{pct(v['kit_classified_pct'])} | {pct(v['naive_detected_pct'])} |")
    return out


def summary_block(c: dict, ce: dict, run: dict) -> list[str]:
    o, t, cfg = c["overall"], c["timing_s"], c["config"]
    s = ce["summary"]
    return [
        f"Campaign: {cfg['scenarios']} seeded scenarios (seed {cfg['seed']}), 0-"
        f"{cfg['max_faults_per_scenario']} random wiring faults each, {cfg['io_points']} I/O points, "
        f"{o['n']} faults in total. Simulated rack and faults.", "",
        "| Metric | Kit (full loop check) | Naive baseline |", "|---|---|---|",
        f"| Faults detected | {o['kit_detected']}/{o['n']} ({pct(o['kit_detected_pct'])}) | "
        f"{o['naive_detected']}/{o['n']} ({pct(o['naive_detected_pct'])}) |",
        f"| Cause classified correctly | {o['kit_classified']}/{o['n']} "
        f"({pct(o['kit_classified_pct'])}) | not attempted |",
        f"| False alarms on healthy points | {o['kit_false_alarms']}/{o['healthy_point_checks']} "
        f"({pct(o['kit_false_alarm_pct'])}) | {o['naive_false_alarms']}/{o['healthy_point_checks']} "
        f"({pct(o['naive_false_alarm_pct'])}) |",
        f"| Wall time per scenario (local OPC UA, this host) | {t['kit_per_scenario']:.2f} s | "
        f"{t['naive_per_scenario']:.2f} s |", "",
        f"Cause-and-effect test: {s['causes']} causes x {s['effects']} effects "
        f"({s['matrix_cells_checked']} matrix cells), {s['checks']} checks, {s['passed']} passed, "
        f"{s['failed']} failed.", "",
        "Read the 100 % figures with care: the fault simulator and the classification rules were "
        "written together, so the campaign shows that the rules separate the seven modelled fault "
        "classes without false alarms. It is not a measure of accuracy on real wiring.", "",
        f"Sample loop check (`config/demo_faults.yaml`, {len(run['injected_faults_simulation_only'])} "
        f"planted faults): {run['summary']['failed']} of {run['summary']['points']} points flagged.",
    ]


def main() -> None:
    c = json.loads((ROOT / "results" / "campaign.json").read_text())
    ce = json.loads((ROOT / "results" / "cetest" / "ce_test_record.json").read_text())
    run = json.loads((ROOT / "results" / "sample_run" / "commissioning_record.json").read_text())
    block = summary_block(c, ce, run)
    env = c["environment"]
    md = ["# Results", "",
          "> Generated by `scripts/make_results.py` from `results/*.json`. Do not edit by hand.",
          "> All numbers come from a SIMULATED rack with simulated wiring faults.", "",
          "## Summary", "", *block, "",
          "## Per fault class", "", *class_table(c["per_class"]), "",
          "## Scaling faults by variant", "",
          *class_table({k: v for k, v in c["per_variant"].items() if k.startswith("scaling")}), "",
          "## Definitions", "",
          "- Detected: at least one point involved in the fault is reported as failed.",
          "- Classified: every point involved is failed with the right cause; for a swap both "
          "points must also name each other.",
          "- False alarm: a point with no injected fault is reported as failed.",
          "- Kit: 5 injection steps (0/25/50/75/100 %) with 3 readings each, cross-talk check on "
          "all channels of the same type, DI/DO in both states.",
          "- Naive: one reading at 50 % per analog point, one state (closed / ON) per digital "
          "point, no cross-talk check, pass/fail only.", "",
          "## Environment", "",
          f"Python {env['python']} on {env['platform']} ({env['processor']}). Total campaign wall "
          f"time {c['timing_s']['total']} s (kit {c['timing_s']['kit']} s, naive "
          f"{c['timing_s']['naive']} s).", ""]
    (ROOT / "docs" / "RESULTS.md").write_text("\n".join(md))
    readme = ROOT / "README.md"
    text = readme.read_text()
    per_class = ["", "Per fault class:", "", *class_table(c["per_class"])]
    new = "<!-- RESULTS:START -->\n" + "\n".join(block + per_class) + "\n<!-- RESULTS:END -->"
    readme.write_text(re.sub(r"<!-- RESULTS:START -->.*?<!-- RESULTS:END -->", new, text,
                             flags=re.S))
    print("wrote docs/RESULTS.md and README results block")


if __name__ == "__main__":
    main()
